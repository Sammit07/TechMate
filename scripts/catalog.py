def kb_catalog() -> list[dict]:
    """All KB articles with stable IDs; also fills Subcategory.kb_ids."""
    articles = []
    n = 10001
    for sub in SUBCATEGORIES:
        sub.kb_ids.clear()
        for title in sub.kb_titles:
            kb_id = f"KB{n:07d}"
            articles.append({"kb_id": kb_id, "title": title, "category": sub.category,
                             "subcategory": sub.name, "group": sub.group, "ci_type": sub.ci_type})
            sub.kb_ids.append(kb_id)
            n += 1
    for category, title, group in GENERAL_KB:
        articles.append({"kb_id": f"KB{n:07d}", "title": title, "category": category,
                         "subcategory": "General", "group": group, "ci_type": ""})
        n += 1
    return articles


