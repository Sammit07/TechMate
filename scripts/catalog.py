# Resolution-time targets (minutes of elapsed time) per priority, used for SLA breach flags.
SLA_MINUTES = {"1 - Critical": 4 * 60, "2 - High": 8 * 60, "3 - Moderate": 24 * 60, "4 - Low": 72 * 60}


@dataclass(frozen=True)
class Subcategory:
    key: str
    category: str
    name: str
    group: str
    share: float                       # relative ticket volume
    priority_weights: tuple            # weights for P1..P4
    fcr_rate: float                    # share solved at first contact by the service desk
    median_minutes: int                # typical time to resolve when not first-contact
    short_descriptions: tuple
    details: tuple                     # sentences combined into the description
    resolutions: tuple                 # close notes
    kb_titles: tuple                   # KB articles for this subcategory
    ci_type: str = "Laptop"            # configuration item the ticket is about
    seasonal: str = ""                 # seasonality tag used when the demo history was generated
    kb_ids: list = field(default_factory=list)


