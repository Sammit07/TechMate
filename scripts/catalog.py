"""The L1 service-desk catalog shared by the data generators.

One place defines categories, subcategories, which support group owns each, how
tickets are worded and resolved, and which knowledge-base articles cover them. The
ticket CSV and the KB PDFs are both generated from this, so they stay consistent.
"""

